#!/usr/bin/env python3
"""Extract the two CoinFT ONNX MLPs into a Teensy-friendly C++ header.

The generated arrays keep the ONNX row-major layout: each dense layer has
``out_features * in_features`` weights and the value at ``out * in + in`` is
the coefficient used for that output neuron.
"""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

import numpy as np
import onnx
from onnx import numpy_helper


LAYER_NAMES = (
    "net.0",
    "net.2",
    "net.4",
    "net.6",
    "net.8",
    "net.10",
)
EXPECTED_SHAPES = ((128, 12), (64, 128), (36, 64), (24, 36), (12, 24), (6, 12))
MODEL_SPECS = {
    "left": "coinft_260804_0001",
    "right": "coinft_260804_0010",
}


def _cpp_float(value: float) -> str:
    if not np.isfinite(value):
        raise ValueError(f"non-finite model value: {value!r}")
    # Nine significant decimal digits round-trip every IEEE-754 float32.
    return f"{float(np.float32(value)):.9g}f"


def _format_array(values: np.ndarray, per_line: int = 8) -> str:
    flat = np.asarray(values, dtype=np.float32).reshape(-1)
    rows = []
    for start in range(0, len(flat), per_line):
        rows.append("    " + ", ".join(_cpp_float(value) for value in flat[start : start + per_line]))
    return ",\n".join(rows)


def _load_model(model_path: Path) -> dict[str, np.ndarray]:
    model = onnx.load(str(model_path), load_external_data=True)
    expected_ops = ("Gemm", "Relu") * 5 + ("Gemm",)
    actual_ops = tuple(node.op_type for node in model.graph.node)
    if actual_ops != expected_ops:
        raise ValueError(f"{model_path}: expected Gemm/ReLU MLP graph, got {actual_ops}")
    for node in model.graph.node:
        if node.op_type != "Gemm":
            continue
        attributes = {item.name: onnx.helper.get_attribute_value(item) for item in node.attribute}
        if attributes.get("transA", 0) != 0 or attributes.get("transB", 0) != 1:
            raise ValueError(f"{model_path}: unsupported Gemm orientation in {node.name}")
        if attributes.get("alpha", 1.0) != 1.0 or attributes.get("beta", 1.0) != 1.0:
            raise ValueError(f"{model_path}: unsupported Gemm scaling in {node.name}")
    input_shape = tuple(dimension.dim_value for dimension in model.graph.input[0].type.tensor_type.shape.dim)
    output_shape = tuple(dimension.dim_value for dimension in model.graph.output[0].type.tensor_type.shape.dim)
    if input_shape != (1, 12) or output_shape != (1, 6):
        raise ValueError(f"{model_path}: expected input (1,12) and output (1,6), got {input_shape} and {output_shape}")
    initializers = {item.name: numpy_helper.to_array(item).astype(np.float32, copy=False) for item in model.graph.initializer}
    result: dict[str, np.ndarray] = {}
    for index, layer in enumerate(LAYER_NAMES):
        weight_name = f"{layer}.weight"
        bias_name = f"{layer}.bias"
        if weight_name not in initializers or bias_name not in initializers:
            raise ValueError(f"{model_path}: missing {weight_name} or {bias_name}")
        weights = initializers[weight_name]
        bias = initializers[bias_name]
        if not np.all(np.isfinite(weights)) or not np.all(np.isfinite(bias)):
            raise ValueError(f"{model_path}: {layer} contains non-finite parameters")
        if tuple(weights.shape) != EXPECTED_SHAPES[index] or tuple(bias.shape) != (EXPECTED_SHAPES[index][0],):
            raise ValueError(
                f"{model_path}: unexpected {layer} shapes {weights.shape} and {bias.shape}; "
                f"expected {EXPECTED_SHAPES[index]} and {(EXPECTED_SHAPES[index][0],)}"
            )
        result[f"w{index}"] = weights
        result[f"b{index}"] = bias
    return result


def _load_norm(norm_path: Path) -> dict[str, np.ndarray]:
    raw = json.loads(norm_path.read_text(encoding="utf-8"))
    result = {}
    for key, size in (("mu_x", 12), ("sd_x", 12), ("mu_y", 6), ("sd_y", 6)):
        if key not in raw:
            raise ValueError(f"{norm_path}: missing {key}")
        values = np.asarray(raw[key], dtype=np.float32)
        if values.shape != (size,) or not np.all(np.isfinite(values)):
            raise ValueError(f"{norm_path}: {key} must contain {size} finite values")
        if key.startswith("sd_") and np.any(values == 0):
            raise ValueError(f"{norm_path}: {key} contains zero")
        result[key] = values
    return result


def _emit_array(name: str, values: np.ndarray) -> str:
    flat = np.asarray(values, dtype=np.float32).reshape(-1)
    return f"alignas(4) static const float {name}[{len(flat)}] = {{\n{_format_array(flat)}\n}};\n"


def generate(repo_root: Path, output: Path) -> None:
    output.parent.mkdir(parents=True, exist_ok=True)
    blocks = [
        "// Generated by tools/generate_model_header.py; do not edit by hand.\n",
        "#pragma once\n",
        "\n",
        "#include <cstddef>\n",
        "\n",
        "namespace coinft_models {\n",
        "constexpr std::size_t kInputSize = 12;\n",
        "constexpr std::size_t kOutputSize = 6;\n",
        "constexpr std::size_t kLayerCount = 6;\n\n",
    ]
    for side, model_id in MODEL_SPECS.items():
        model_dir = repo_root / "models (3) (1)" / model_id
        model_path = model_dir / "CFT24_MLP.onnx"
        external_data_path = Path(str(model_path) + ".data")
        norm_path = model_dir / "CFT24_norm.json"
        model = _load_model(model_path)
        norm = _load_norm(norm_path)
        prefix = f"{side}_"
        blocks.append(f"// {side}: {model_id}\n")
        blocks.append(f"// ONNX SHA-256: {hashlib.sha256(model_path.read_bytes()).hexdigest()}\n")
        if external_data_path.is_file():
            blocks.append(f"// ONNX external data SHA-256: {hashlib.sha256(external_data_path.read_bytes()).hexdigest()}\n")
        blocks.append(f"// Normalization SHA-256: {hashlib.sha256(norm_path.read_bytes()).hexdigest()}\n")
        blocks.append(_emit_array(prefix + "mu_x", norm["mu_x"]))
        blocks.append(_emit_array(prefix + "sd_x", norm["sd_x"]))
        blocks.append(_emit_array(prefix + "mu_y", norm["mu_y"]))
        blocks.append(_emit_array(prefix + "sd_y", norm["sd_y"]))
        for index in range(6):
            blocks.append(_emit_array(prefix + f"w{index}", model[f"w{index}"]))
            blocks.append(_emit_array(prefix + f"b{index}", model[f"b{index}"]))
        blocks.append("\n")
    blocks.append("}  // namespace coinft_models\n")
    output.write_text("\n".join(blocks), encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--repo-root", type=Path, default=Path(__file__).resolve().parents[2])
    parser.add_argument(
        "--output",
        type=Path,
        default=Path(__file__).resolve().parents[1] / "firmware" / "teensy_coinft_mlp" / "model_params.h",
    )
    args = parser.parse_args()
    generate(args.repo_root.resolve(), args.output.resolve())
    print(args.output.resolve())
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
